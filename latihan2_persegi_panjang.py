panjang = float(input("Panjang : "))
lebar = float(input("Lebar   : "))

luas_persegi = panjang * lebar
keliling_persegi = 2 * (panjang + lebar)

print(f"Output  : Luas : {luas_persegi} m2, Keliling : {keliling_persegi} m")

